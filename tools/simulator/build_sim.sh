#!/bin/sh
# Builds the browser simulator core from the firmware's own C sources.
#   1. clang (zig cc) -> WebAssembly       2. binaryen wasm2js -> plain JavaScript
# Plain JS runs from file:// and inside strict web pages without WASM support.
# Needs: python3 -m pip install ziglang ; npm i -g binaryen  (or set WASM2JS=path/to/wasm2js)
set -e
cd "$(dirname "$0")/../.."
SRC="tools/simulator/sim_board.c src/app/app_fsm.c src/app/fan_logic.c src/middleware/pid.c \
     src/middleware/ramp.c src/middleware/fault.c src/middleware/modbus_slave.c src/middleware/crc.c \
     src/middleware/telemetry.c src/middleware/datalog.c src/middleware/cli.c \
     src/drivers/w25qxx.c src/drivers/sht3x.c src/drivers/ssd1306.c"
INC="-Isrc/common -Isrc/app -Isrc/middleware -Isrc/drivers"
OUT=tools/simulator/build
mkdir -p $OUT
python3 -m ziglang cc -target wasm32-wasi -mexec-model=reactor -mcpu=mvp -Os -s -std=gnu11 -Wall $INC $SRC -o $OUT/fan_sim.wasm
${WASM2JS:-wasm2js} $OUT/fan_sim.wasm -O2 -o $OUT/fan_sim_es.js
{
  echo "/* Generated by build_sim.sh from the firmware C sources. Do not edit. */"
  echo "(function () {"
  echo "var wasi_snapshot_preview1 = { random_get: function () { return 0; } };"
  grep -v "^import \|^export var" $OUT/fan_sim_es.js
  echo "window.FanSimCore = retasmFunc;"
  echo "})();"
} > tools/simulator/fan_sim_core.js
echo "ok: tools/simulator/fan_sim_core.js"
# native smoke test:  gcc $INC $SRC tools/simulator/sim_main.c -lm -o sim && ./sim
